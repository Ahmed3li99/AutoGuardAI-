        what_ar = f"قراءة {ar_name} وصلت لـ {peak:.1f} {unit_ar}، يعني {word_ar}، {when_ar}."
        what_en = f"{en_name} reached {peak:.1f} {unit}, {word_en} than expected, {when_en}."
