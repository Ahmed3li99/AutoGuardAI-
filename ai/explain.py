MODEL_INPUTS = ["rpm", "speed_kmh", "coolant_temp_c", "engine_load_pct", "throttle_pct",
                "manifold_pressure_kpa", "intake_air_temp_c", "battery_voltage"]


def coverage(result: AnalysisResult | None, session: NormalizedSession, quality: dict | None) -> list[dict]:
    """How much the verdict can be trusted: checks that ran, sensors available,
    share of valid data, and whether the models' calibration fits this car.
    Each row: {ar, en, value_ar, value_en, ok (True/False/None)}."""
    rows = []
    if result is not None:
        ran, missed = checks_ran(result)
        total = len(ran) + len(missed)
        rows.append({"ar": "الفحوصات اللي اشتغلت", "en": "Checks that ran",
                     "value_ar": f"{len(ran)} من {total}: " + "، ".join(CHECK_NAMES.get(k, (k, k))[0] for k in ran),
                     "value_en": f"{len(ran)} of {total}: " + ", ".join(CHECK_NAMES.get(k, (k, k))[1] for k in ran),
                     "ok": not missed})
    have = [s for s in MODEL_INPUTS if s in session.signals]
    lack = [s for s in MODEL_INPUTS if s not in session.signals]
    rows.append({"ar": "الحساسات المتاحة", "en": "Sensors available",
                 "value_ar": f"{len(have)} من {len(MODEL_INPUTS)}" + (
                     " — ناقص: " + "، ".join(NAMES.get(s, (s, s, ""))[0] for s in lack) if lack else ""),
                 "value_en": f"{len(have)} of {len(MODEL_INPUTS)}" + (
                     " — missing: " + ", ".join(NAMES.get(s, (s, s, ""))[1] for s in lack) if lack else ""),
                 "ok": not lack})
    if quality and quality.get("signals"):
        sig = [s for s in quality["signals"] if s["name"] in have] or quality["signals"]
        valid = 1.0 - float(np.mean([s["missing_rate"] for s in sig]))
        gaps = quality.get("n_gaps", 0)
        rows.append({"ar": "نسبة الداتا الصالحة", "en": "Valid data",
                     "value_ar": f"{100 * valid:.0f}%" + (f" — فيه {gaps} انقطاع في التسجيل" if gaps else ""),
                     "value_en": f"{100 * valid:.0f}%" + (f" — {gaps} gap(s) in the recording" if gaps else ""),
                     "ok": valid >= 0.95 and not gaps})
    if result is not None:
        ml = {k: s for k, s in result.detector_status.items() if k != "rules" and s.get("status") == "ok"}
        if not ml:
            rows.append({"ar": "مناسبة الموديلات للعربية دي", "en": "Model fit for this car",
                         "value_ar": "مفيش موديلات اشتغلت", "value_en": "no model ran", "ok": False})
        elif ml.get("expected_vs_actual", {}).get("calibration") == "calibrated_personal":
            helpers = [k for k, s in ml.items() if s.get("calibration") == "uncalibrated_for_this_data"]
            rows.append({"ar": "مناسبة الموديلات للعربية دي", "en": "Model fit for this car",
                         "value_ar": "مناسبة — الموديل الأساسي اتعلّم على عربيتك من رحلاتها المرجعية" + (
                             " (الموديلات المساعدة لسه متظبطة على تويوتا)" if helpers else ""),
                         "value_en": "good — the main model was learned from YOUR car's reference trips" + (
                             " (helper models are still calibrated on the Toyota)" if helpers else ""), "ok": True})
        elif all(s.get("calibration") == "calibrated" for s in ml.values()):
            rows.append({"ar": "مناسبة الموديلات للعربية دي", "en": "Model fit for this car",
                         "value_ar": "مناسبة — نفس عربية التدريب (تويوتا إتيوس)",
                         "value_en": "good — same car the models were trained on (Toyota Etios)", "ok": True})
        else:
            rows.append({"ar": "مناسبة الموديلات للعربية دي", "en": "Model fit for this car",
                         "value_ar": "غير مضمونة — الموديلات اتعلمت على عربية تانية، فالحدود ممكن تبقى مش دقيقة",
                         "value_en": "uncertain — models were trained on a different car, limits may not fit",
                         "ok": False})
    rows.append({"ar": "مدة الرحلة كفاية للموديلات؟", "en": "Trip long enough for the models?",
                 "value_ar": "أيوه" if session.duration_s >= MIN_MODEL_SECONDS else "لأ (أقل من دقيقة)",
                 "value_en": "yes" if session.duration_s >= MIN_MODEL_SECONDS else "no (under one minute)",
                 "ok": session.duration_s >= MIN_MODEL_SECONDS})
    return rows
